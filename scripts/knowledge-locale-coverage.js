// Knowledge catalog language coverage: for every enabled pack and rule, the interface
// languages in which the tests resolve the rule from localized Business Central captions,
// the languages with an explanation, and the languages whose Microsoft Learn source is
// missing. Writes docs/KNOWLEDGE_LOCALE_COVERAGE.md; --check fails when it is out of date.
"use strict";
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const target = path.join(root, "docs", "KNOWLEDGE_LOCALE_COVERAGE.md");
const check = process.argv.includes("--check");
const languages = require("../src/engine/language-registry");
const LOCALES = languages.supported().map(item => item.locale);
const SHORT = Object.fromEntries(LOCALES.map(locale => [locale.slice(0, 2), locale]));

// Every test that loads the knowledge modules, run with the tracer preloaded.
function trace() {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "knowledge-coverage-")), "trace.tsv");
  const tests = fs.readdirSync(path.join(root, "tests")).filter(name => name.endsWith(".test.js"))
    .filter(name => /knowledge-domain|knowledge-repository/.test(
      fs.readFileSync(path.join(root, "tests", name), "utf8"))).sort();
  const failed = [];
  for (const name of tests) {
    try {
      execFileSync(process.execPath, ["-r", path.join(__dirname, "knowledge-coverage-trace.js"),
        path.join("tests", name)], { cwd: root, stdio: "ignore", timeout: 180000,
        env: { ...process.env, KNOWLEDGE_COVERAGE_TRACE: file } });
    } catch { failed.push(name); }
  }
  if (failed.length) throw new Error(`Knowledge tests failed while tracing: ${failed.join(", ")}`);
  const tested = new Map();
  const lines = fs.existsSync(file) ? fs.readFileSync(file, "utf8").split("\n") : [];
  for (const line of lines.filter(Boolean)) {
    const [ruleId, raw] = line.split("\t");
    const locale = LOCALES.find(item => item.toLowerCase() === raw.toLowerCase()) ||
      SHORT[raw.toLowerCase().slice(0, 2)];
    if (!locale) continue;
    if (!tested.has(ruleId)) tested.set(ruleId, new Set());
    tested.get(ruleId).add(locale);
  }
  return { tested, testCount: tests.length };
}

function packs() {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, "src/knowledge-packs/index.json"), "utf8"));
  return manifest.packs.filter(item => item.enabled).map(item =>
    JSON.parse(fs.readFileSync(path.join(root, "src", item.file), "utf8")));
}

// The pack records, for a source, the languages in which Microsoft Learn has no localized
// counterpart; a rule has that gap when any of its sources records it.
function sourceGaps(pack, rule) {
  const gaps = pack.sourceLocaleGaps || {};
  const recorded = new Set((rule.sourceIds || []).flatMap(id => gaps[id] || []));
  return new Set(LOCALES.filter(locale => recorded.has(locale)));
}

function render({ tested, testCount }) {
  const short = locale => locale.slice(0, 2);
  const all = packs().filter(pack => (pack.rules || []).length);
  const lines = [
    "# Knowledge catalog language coverage", "",
    "Generated by `npm run knowledge:coverage` from the enabled packs and the knowledge tests. Do not edit by hand; `node scripts/knowledge-locale-coverage.js --check` reports when this file is out of date.", "",
    `A rule counts as runtime-covered in a language when one of the ${testCount} knowledge tests resolves it from captions in that language. A rule can also match captions no test exercises. Untested languages are listed as gaps: they are not claimed as supported. An explanation in a language does not verify its Business Central captions.`, "",
    "## Runtime caption coverage per pack", "",
    `| Pack | Rules | ${LOCALES.map(short).join(" | ")} |`,
    `|---|---:|${LOCALES.map(() => "---:").join("|")}|`
  ];
  const totals = Object.fromEntries(LOCALES.map(locale => [locale, 0]));
  let ruleTotal = 0;
  for (const pack of all) {
    const rules = pack.rules;
    ruleTotal += rules.length;
    const counts = LOCALES.map(locale => {
      const count = rules.filter(rule => tested.get(rule.ruleId)?.has(locale)).length;
      totals[locale] += count;
      return count;
    });
    lines.push(`| ${pack.packId} | ${rules.length} | ${counts.join(" | ")} |`);
  }
  lines.push(`| **All packs** | **${ruleTotal}** | ${LOCALES.map(locale => `**${totals[locale]}**`).join(" | ")} |`, "");

  // Explanation coverage in every language is enforced by knowledge-explanation-coverage.
  lines.push("## Missing localized Microsoft Learn sources", "",
    "| Pack | Rules and the languages without a localized Learn page |", "|---|---|");
  for (const pack of all) {
    const sources = pack.rules.map(rule => [rule, sourceGaps(pack, rule)]).filter(([, gaps]) => gaps.size);
    if (sources.length) lines.push(`| ${pack.packId} | ${sources.map(([rule, gaps]) =>
      `${rule.ruleId} (${[...gaps].map(short).join(", ")})`).join("; ")} |`);
  }
  lines.push("");

  lines.push("## Gaps by rule", "",
    "Languages in which no test resolves the rule. *No Learn page* marks languages without a localized Microsoft Learn page for the rule's sources.", "");
  for (const pack of all) {
    const rows = pack.rules.map(rule => {
      const covered = tested.get(rule.ruleId) || new Set();
      const missing = LOCALES.filter(locale => !covered.has(locale));
      return { rule, covered, missing, noPage: sourceGaps(pack, rule) };
    }).filter(row => row.missing.length);
    if (!rows.length) continue;
    lines.push(`### ${pack.packId}`, "", "| Rule | Tested | Missing |", "|---|---|---|");
    for (const { rule, covered, missing, noPage } of rows) {
      const testedText = LOCALES.filter(locale => covered.has(locale)).map(short).join(", ") || "none";
      const missingText = missing.length === LOCALES.length ? "all" : missing.map(locale =>
        noPage.has(locale) ? `${short(locale)} (no Learn page)` : short(locale)).join(", ");
      lines.push(`| ${rule.ruleId} | ${testedText} | ${missingText} |`);
    }
    lines.push("");
  }

  lines.push("## Where localized captions come from", "",
    "Localized captions are taken from Business Central's own translation files: the Microsoft language apps for Base Application and the translations shipped in the first-party apps (E-Document Core, Quality Management, Shopify Connector, Subscription Billing and Sustainability), version 28.1 (W1). The English caption a rule already matches identifies the page, action or field; the same translation unit gives its caption in every language. `tests/fixtures/knowledge-localized-captions.json` holds one case per rule and language with the translation units it was read from, and `tests/knowledge-localized-captions.test.js` checks that each language resolves as English does.", "",
    "Actions the client itself provides (*New*, *OK*, *Yes*, *Delete*, *Edit*, *Back* and the *Open record* tooltip) are taken from the Business Central web client's language resources (`Microsoft.Dynamics.Framework.Resource.js`, platform 26.18.55014.0); the fixture names their resource keys. The client's *New* is *Créer* in French, not *Nouveau*.", "",
    "Localized Microsoft Learn pages are not used for captions. They are partly machine-translated and disagree with the product (Learn's Swedish *Överför GL-poster till CA* is *Överför redovisningstransaktioner till kostnadsredovisning* in Business Central).", "",
    "The remaining gaps are:", "",
    "- Rules whose captions are not in the Business Central 28.1 translation files, such as *Applied Sales Price and Discount*, *Manual Price*, *Change Applied Unit Price*, *Apply Purchase Prices and Discounts*, *Run Cost Allocation*, *Block Lot in the Inspection* and *Show Inspections for Item and Document*. They may come from another version, an extension or a recording; they are not expanded until a source confirms them.",
    "- Rules whose English patterns are generic or not anchored, which are not expanded automatically.",
    "- Aptean add-on rules. They match the captions in Aptean's product documentation (erpdocs.apteancloud.com/bc), which is published in English only, so other languages cannot be verified from a public source.",
    "- Observed workflows recorded in a tenant, which have no Microsoft translation source.",
    "- Captions that differ between a list and a card: German uses *Lagerkommissionierung erstellen* for both inventory and warehouse picks on the project list, so only the project card's distinct captions are matched.", "",
    "Captions recorded in a tenant with that language installed can close these gaps; each needs a runtime test.", "");
  return lines.join("\n");
}

const content = render(trace());
if (check) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== content) {
    console.error("docs/KNOWLEDGE_LOCALE_COVERAGE.md is out of date. Run npm run knowledge:coverage.");
    process.exitCode = 1;
  } else console.log("Knowledge locale coverage is up to date.");
} else {
  fs.writeFileSync(target, content);
  console.log(`Wrote ${path.relative(root, target)}.`);
}
